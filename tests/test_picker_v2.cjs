'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={window:{},document:{readyState:'loading',addEventListener(){}}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','picker_v2.js'),'utf8'),context);
const engine=context.window.Nota59PickerV2;
const product=(name,extra={})=>({name,brand:'Test',price5:500,price10:1000,...extra});
const names=['Creed Aventus','Amouage Interlude Man','Tom Ford Ombré Leather EDP','Initio Wild Rush','Kilian Angels Share','Maison Crivelli Oud Maracuja','Xerjoff Naxos','Parfums de Marly Herod','Tom Ford Soleil Blanc EDP','Parfums de Marly Althair','Ex Nihilo Blue Talisman','Ex Nihilo Blue Talisman Extrait'];
const payload={items:names.map(name=>product(name,name==='Kilian Angels Share'?{available:false}:{}))};
assert.equal(engine.directions.length,10);
for(const occasion of ['На каждый день','На вечер',''])for(const direction of [...engine.directions,'']){
 const result=engine.recommend(payload,occasion,direction);
 assert.equal(result.loading,false);assert.equal(result.unprofiled,0);
 assert.ok(result.items.every(m=>m.product.available!==false&&m.product.name!=='Ex Nihilo Blue Talisman'));
 assert.ok(result.items.every((m,i,a)=>!i||a[i-1].score>=m.score));
 assert.equal(JSON.stringify(result),JSON.stringify(engine.recommend(payload,occasion,direction)));
}
const strength=(name,direction)=>engine.recommend({items:[product(name)]},'',direction).items[0]?.strength||0;
assert.equal(strength('Initio Wild Rush','Свежий'),2);
assert.equal(strength('Initio Wild Rush','Сладкий'),2);
assert.equal(strength('Initio Wild Rush','Гурманский'),1);
assert.equal(strength('Xerjoff Naxos','Табачный'),2);
assert.equal(strength('Xerjoff Naxos','Сладкий'),1);
assert.equal(strength('Parfums de Marly Herod','Табачный'),2);
assert.equal(strength('Parfums de Marly Herod','Пряный'),1);
assert.equal(strength('Maison Crivelli Oud Maracuja','Фруктовый'),2);
assert.equal(strength('Maison Crivelli Oud Maracuja','Кожаный'),2);
assert.equal(strength('Tom Ford Soleil Blanc EDP','Гурманский'),0);
assert.equal(strength('Parfums de Marly Althair','Гурманский'),2);
assert.equal(strength('Ex Nihilo Blue Talisman Extrait','Цветочный'),2);
assert.equal(engine.recommend(null).loading,true);
assert.equal(engine.recommend({items:[product('Mystery')]}).unprofiled,1);
assert.equal(engine.recommend({items:[product('Tom Ford Ombré Leather Parfum')]}).unprofiled,1);
assert.equal(strength('Tom Ford Ombre\u0301 Leather EDP','Кожаный'),2);
assert.equal(engine.recommend({items:[product('Creed Aventus',{price5:'500',price10:0})]}).items.length,0);
assert.equal(engine.recommend({items:[payload.items[0],payload.items[0]]}).items.length,1);
assert.equal(strength('Creed Aventus','Дымный'),0);
assert.throws(()=>engine.recommend(payload,'invalid',''));
assert.throws(()=>engine.recommend(payload,'','invalid'));
assert.ok(engine.recommend({items:[product('Parfums de Marly Herod')]},'','Табачный').items[0].note.includes('ассоциация'));
console.log('Calibrated picker tests passed: 33 answer combinations and profile regressions.');
